import { test, expect } from '@playwright/test';
import { chooseOption } from './select-helpers';
test('one item shares its deadline, time block and completion across list, calendar and reload', async ({ page }) => {
  await page.goto('/#interfaces'); await page.evaluate(() => { localStorage.removeItem('molr-assistant-prototype-v1'); localStorage.setItem('molr-ui-design-locale', 'en'); }); await page.reload();
  const ui = page.locator('#interfaces').getByRole('tabpanel').first().locator(':scope > div:not([hidden])');
  const nav = ui.getByRole('navigation', { name: 'Workspace navigation' });
  await expect(nav.getByRole('button', { name: 'Todos', exact: true })).toHaveCount(0);
  await expect(nav.getByRole('button', { name: 'Schedule', exact: true })).toHaveCount(0);
  await nav.getByRole('button', { name: 'Plans', exact: true }).click();
  await ui.getByRole('button', { name: 'New plan', exact: true }).click();
  const form = ui.getByRole('form', { name: 'Plan editor' });
  await form.getByLabel('What needs doing?', { exact: true }).fill('Write report');
  await form.getByLabel('Due date (optional)').fill('2026-10-02');
  await form.getByLabel('Schedule time', { exact: true }).check();
  await form.getByLabel('Start time', { exact: true }).fill('2026-10-01T14:00');
  await form.getByLabel('End time', { exact: true }).fill('2026-10-01T15:00');
  await form.getByRole('button', { name: 'Save plan' }).click();
  await ui.getByRole('group', { name: 'Plan view' }).getByRole('button', { name: 'Calendar' }).click();
  await ui.getByLabel('View date').fill('2026-10-01');
  const row = ui.locator('.plan-row').filter({ hasText: 'Write report' });
  await expect(row).toHaveCount(1); await row.getByRole('checkbox').check();
  await ui.getByLabel('View date').fill('2026-10-02'); await expect(row.getByRole('checkbox')).toBeChecked();
  await ui.getByRole('group', { name: 'Plan view' }).getByRole('button', { name: 'List', exact: true }).click();
  await expect(row.getByRole('checkbox')).toBeChecked();
  await page.reload(); await nav.getByRole('button', { name: 'Plans', exact: true }).click(); await expect(row.getByRole('checkbox')).toBeChecked();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('molr-assistant-prototype-v1')!));
  expect(saved.todos.filter((r: { title: string }) => r.title === 'Write report')).toHaveLength(1);
  expect(saved.schedules.filter((r: { title: string }) => r.title === 'Write report')).toHaveLength(0);
  await row.getByRole('button', { name: 'Edit', exact: true }).click(); await form.getByLabel('Schedule time', { exact: true }).uncheck(); await form.getByRole('button', { name: 'Save plan' }).click();
  await ui.getByRole('group', { name: 'Plan view' }).getByRole('button', { name: 'Calendar' }).click();
  await ui.getByLabel('View date').fill('2026-10-01'); await expect(row).toHaveCount(0);
  await ui.getByLabel('View date').fill('2026-10-02'); await expect(row).toHaveCount(1);
  await chooseOption(ui.getByRole('combobox', { name: 'Status', exact: true }), 'Open'); await expect(row).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
