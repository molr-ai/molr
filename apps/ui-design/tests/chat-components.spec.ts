import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { chooseOption } from './select-helpers';

function example(page: Page, name: string) {
  return page.locator('.chat-showcase .component-example').filter({ has: page.getByRole('heading', { name, exact: true }) });
}
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('molr-ui-design-locale', 'en'));
  await page.goto('/#components');
  await page.getByRole('tablist', { name: 'Component categories', exact: true }).getByRole('tab', { name: 'Chat', exact: true }).click();
});

test('chat composer handles drafts, IME, attachments and disabled states without changing assistant data', async ({ page }) => {
  const before = await page.evaluate(() => localStorage.getItem('molr-assistant-prototype-v1'));
  const composer = example(page, 'Message composer');
  const input = composer.getByRole('textbox', { name: 'Message your assistant' });
  const initialHeight = (await input.boundingBox())!.height;
  await input.fill('A quiet outing\nWith time to rest\nNear a park');
  expect((await input.boundingBox())!.height).toBeGreaterThan(initialHeight);
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true });
  await expect(input).toHaveValue('A quiet outing\nWith time to rest\nNear a park');
  await composer.locator('input[type=file]').setInputFiles([
    { name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('notes') },
    { name: 'extra.txt', mimeType: 'text/plain', buffer: Buffer.from('extra') },
  ]);
  await composer.getByRole('button', { name: 'Remove attachment extra.txt' }).click();
  await expect(composer.locator('.composer-attachments')).not.toContainText('extra.txt');
  await chooseOption(composer.getByRole('combobox', { name: 'Select model' }), 'Fast · Demo');
  await composer.getByRole('switch', { name: 'Lock composer' }).check();
  const locked = composer.getByRole('group', { name: 'Message input is locked' });
  await expect(locked).toBeVisible();
  await expect(input).toHaveCount(0);
  await expect(composer.getByRole('button', { name: 'Send', exact: true })).toHaveCount(0);
  await expect(composer.locator('input[type=file]')).toHaveCount(0);
  await expect(composer.locator('.composer-attachments')).toHaveCount(0);
  await locked.getByRole('button', { name: 'Unlock composer' }).focus();
  await page.keyboard.press('Enter');
  await expect(input).toHaveValue('A quiet outing\nWith time to rest\nNear a park');
  expect((await input.boundingBox())!.height).toBeGreaterThan(initialHeight);
  await expect(composer.locator('.composer-attachments')).toContainText('notes.txt');
  await composer.getByRole('switch', { name: 'Disable composer' }).check();
  await expect(input).toBeDisabled();
  await expect(composer.getByRole('button', { name: 'Send', exact: true })).toBeDisabled();
  await composer.getByRole('switch', { name: 'Disable composer' }).uncheck();
  await composer.getByRole('button', { name: 'Send', exact: true }).click();
  await expect(input).toHaveValue('');
  expect((await input.boundingBox())!.height).toBe(initialHeight);
  await expect(composer.locator('.chat-sent-preview')).toContainText('A quiet outing');
  await expect(composer.locator('.chat-sent-preview')).toContainText('notes.txt');
  await expect(composer.locator('.chat-sent-preview')).not.toContainText('extra.txt');
  await composer.getByRole('button', { name: 'Voice input' }).click();
  await expect(composer.getByRole('button', { name: 'Send', exact: true })).toBeDisabled();
  await expect(composer.locator('.composer-notice')).toContainText('microphone is not used');
  await composer.getByRole('button', { name: 'Stop recording' }).click();
  await expect(composer.locator('.composer-attachments')).toContainText('voice-demo.webm');
  expect(await page.evaluate(() => localStorage.getItem('molr-assistant-prototype-v1'))).toBe(before);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('conversation supports stopping and following up; cards and information stay outside bubbles', async ({ page }, info) => {
  const preview = example(page, 'Conversation preview');
  const log = preview.getByRole('log', { name: 'Example conversation' });
  await expect(log.locator('.ui-chat-bubble .ui-chat-card')).toHaveCount(0);
  await expect(log.locator('.message-cards > .ui-chat-card')).toHaveCount(1);
  const input = preview.getByRole('textbox', { name: 'Message your assistant' });
  await input.fill('Add a lunch stop');
  await input.press('Enter');
  await expect(log.locator('.ui-chat-message--assistant').last()).toContainText('Got');
  await expect(log.locator('.ui-chat-message--user .message-read-status').last()).toHaveText('Read');
  await preview.getByRole('button', { name: 'Pause current execution' }).click();
  await expect(preview.locator('.composer-notice')).toContainText('Generation stopped');
  const stoppedText = await log.locator('.ui-chat-message--assistant').last().textContent();
  await input.fill('Make it vegetarian');
  await input.press('Enter');
  await expect(log.locator('.ui-chat-message--assistant').last()).toContainText('without calling a live model', { timeout: 10_000 });
  await expect(preview.getByRole('button', { name: 'Pause current execution' })).toHaveCount(0);
  expect(await log.locator('.ui-chat-message--assistant').nth(1).textContent()).toBe(stoppedText);
  const bubbles = example(page, 'Message bubbles');
  await bubbles.getByRole('button', { name: 'Like', exact: true }).click();
  const like = bubbles.getByRole('button', { name: 'Like', exact: true });
  const dislike = bubbles.getByRole('button', { name: 'Dislike', exact: true });
  await expect(like).toHaveAttribute('aria-pressed', 'true');
  await expect(like.locator('[data-animate]')).toHaveCount(0);
  const likedStroke = await like.locator('.message-feedback__glyph').evaluate(el => getComputedStyle(el).stroke);
  expect(likedStroke).not.toBe('none');
  await expect(like.locator('.message-feedback__cuff')).toHaveCSS('fill', likedStroke);
  await bubbles.screenshot({ path: `/tmp/molr-chat-like-${info.project.name}.png` });
  await dislike.click();
  await expect(dislike).toHaveAttribute('aria-pressed', 'true');
  await expect(like).toHaveAttribute('aria-pressed', 'false');
  await expect(dislike.locator('[data-animate]')).toHaveCount(0);
  const dislikedStroke = await dislike.locator('.message-feedback__glyph').evaluate(el => getComputedStyle(el).stroke);
  expect(dislikedStroke).not.toBe('none');
  expect(dislikedStroke).not.toBe(likedStroke);
  await expect(dislike.locator('.message-feedback__cuff')).toHaveCSS('fill', dislikedStroke);
  await dislike.press('Space');
  await expect(dislike).toHaveAttribute('aria-pressed', 'false');
  await expect(dislike.locator('[data-animate]')).toHaveCount(0);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await like.press('Enter');
  await expect(like).toHaveAttribute('aria-pressed', 'true');
  await expect(like.locator('.message-feedback__motion')).toHaveCSS('animation-name', 'none');
  await expect(like.locator('.message-feedback__accent')).toBeHidden();
  await bubbles.getByRole('button', { name: 'Message information' }).click();
  const details = page.getByRole('dialog', { name: 'Message information', exact: true });
  await expect(details).toContainText('320 ms');
  await expect(details).toContainText('Sample measurements');
  await page.keyboard.press('Escape');
  const cards = example(page, 'Message cards');
  const task = cards.getByRole('button', { name: 'View task' });
  await task.click();
  const drawer = page.getByRole('dialog', { name: 'Task details', exact: true });
  await drawer.getByRole('button', { name: 'Advance sample' }).click();
  await expect(drawer.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '75');
  await page.keyboard.press('Escape');
  await expect(task).toBeFocused();
  await expect(cards.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '75');
  await cards.getByRole('button', { name: 'Preview deliverable' }).click();
  const file = page.getByRole('dialog', { name: 'Deliverable preview', exact: true });
  await expect(file).toContainText('a park walk');
  const download = page.waitForEvent('download');
  await file.getByRole('link', { name: 'Download sample' }).click();
  expect((await download).suggestedFilename()).toBe('weekend-checklist.md');
  await page.keyboard.press('Escape');
  await preview.screenshot({ path: `/tmp/molr-chat-gallery-${info.project.name}.png` });
  await bubbles.screenshot({ path: `/tmp/molr-chat-bubbles-${info.project.name}.png` });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('avatar and sender visibility are independent, and assistant status responds to selection', async ({ page }, info) => {
  const bubbles = example(page, 'Message bubbles');
  await expect(bubbles.getByRole('img', { name: "Molr's avatar" })).toBeVisible();
  await expect(bubbles.getByRole('img', { name: 'Your avatar' })).toBeVisible();
  await expect(bubbles.locator('.ui-chat-bubble .ui-chat-avatar')).toHaveCount(0);
  await bubbles.getByRole('switch', { name: 'Show sender', exact: true }).uncheck();
  await expect(bubbles.locator('.message-sender')).toHaveCount(0);
  await expect(bubbles.getByRole('img', { name: "Molr's avatar" })).toBeVisible();
  await bubbles.getByRole('switch', { name: 'Show avatars', exact: true }).uncheck();
  await expect(bubbles.locator('.ui-chat-avatar')).toHaveCount(0);
  await bubbles.getByRole('switch', { name: 'Show sender', exact: true }).check();
  await expect(bubbles.locator('.message-sender')).toHaveCount(2);
  await bubbles.getByRole('switch', { name: 'Show avatars', exact: true }).check();
  const statuses = example(page, 'Assistant status');
  const status = statuses.getByRole('status');
  await expect(status).toContainText('Browsing files');
  await statuses.getByRole('radio', { name: 'Thinking', exact: true }).check();
  await expect(status).toContainText('Thinking');
  await statuses.getByRole('switch', { name: 'Compact display' }).check();
  await expect(status).toContainText('Considering your request');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  expect(await status.locator('.ui-chat-status__icon').evaluate(el => getComputedStyle(el).animationName)).toBe('none');
  await statuses.getByRole('radio', { name: 'Thinking', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  await expect(status).toContainText('Typing');
  await statuses.getByRole('radio', { name: 'Complete', exact: true }).check();
  await expect(status).toContainText('Your deliverable is ready');
  await statuses.getByRole('radio', { name: 'Action', exact: true }).check();
  await statuses.getByRole('switch', { name: 'Compact display' }).uncheck();
  await statuses.screenshot({ path: `/tmp/molr-chat-status-${info.project.name}.png` });
  await bubbles.screenshot({ path: `/tmp/molr-chat-avatars-${info.project.name}.png` });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('pasted images share attachment previews and a keyboard-accessible multi-image gallery', async ({ page }, info) => {
  const composer = example(page, 'Message composer');
  const input = composer.getByRole('textbox', { name: 'Message your assistant' });
  await input.fill('Keep this draft');
  const paste = async (images: boolean, text = '') => input.evaluate((element, data) => {
    const clipboardData = new DataTransfer();
    if (data.text) clipboardData.setData('text/plain', data.text);
    if (data.images) for (const name of ['first.svg', 'second.svg']) clipboardData.items.add(new File(['<svg xmlns="http://www.w3.org/2000/svg" width="200" height="100"><rect width="200" height="100" fill="seagreen"/></svg>'], name, { type: 'image/svg+xml' }));
    const event = new ClipboardEvent('paste', { clipboardData, bubbles: true, cancelable: true });
    element.dispatchEvent(event); return event.defaultPrevented;
  }, { images, text });
  expect(await paste(false, 'plain text')).toBe(false);
  expect(await paste(true)).toBe(true);
  await expect(composer.locator('.composer-attachments .ui-image-gallery__thumbnail')).toHaveCount(2);
  await expect(input).toHaveValue('Keep this draft');
  await composer.locator('input[type=file]').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('notes') });
  const trigger = composer.getByRole('button', { name: 'Preview image second.svg', exact: true });
  await trigger.click();
  const gallery = page.getByRole('dialog', { name: 'Image preview', exact: true });
  await expect(gallery.getByRole('status')).toHaveText('2 / 2');
  await page.keyboard.press('ArrowLeft');
  await expect(gallery.getByRole('status')).toHaveText('1 / 2');
  await gallery.getByRole('button', { name: 'Next image', exact: true }).click();
  await expect(gallery.getByRole('status')).toHaveText('2 / 2');
  await expect(gallery.locator('.ui-image-gallery__stage img')).toHaveJSProperty('naturalWidth', 200);
  await gallery.screenshot({ path: `/tmp/molr-image-preview-${info.project.name}.png` });
  await page.keyboard.press('Escape');
  await expect(trigger).toBeFocused();
  await composer.getByRole('button', { name: 'Remove attachment first.svg', exact: true }).click();
  await expect(composer.locator('.composer-attachments .ui-image-gallery__thumbnail')).toHaveCount(1);
  await composer.getByRole('switch', { name: 'Disable composer' }).check();
  expect(await paste(true)).toBe(false);
  await composer.getByRole('switch', { name: 'Disable composer' }).uncheck();
  await composer.getByRole('button', { name: 'Voice input' }).click();
  expect(await paste(true)).toBe(false);
  await composer.getByRole('button', { name: 'Stop recording' }).click();
  await composer.getByRole('button', { name: 'Send', exact: true }).click();
  const message = composer.locator('.chat-sent-preview');
  await expect(message.getByRole('button', { name: 'Preview image second.svg', exact: true })).toBeVisible();
  await expect(message).toContainText('notes.txt');
  await message.getByRole('button', { name: 'Preview image second.svg', exact: true }).click();
  await expect(gallery.getByRole('status')).toHaveText('1 / 1');
  await expect(gallery.getByRole('button', { name: 'Next image' })).toHaveCount(0);
  await page.keyboard.press('Escape');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
