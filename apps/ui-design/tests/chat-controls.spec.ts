async function setup(page: Page, mobile = false) { await page.goto('/#interfaces'); await page.evaluate(() => { localStorage.removeItem('molr-assistant-prototype-v1'); localStorage.setItem('molr-ui-design-locale', 'en'); }); await page.reload(); if (mobile) await page.locator('#interfaces').getByRole('tab', { name: 'Mobile', exact: true }).click(); const panel = page.locator('#interfaces').getByRole('tabpanel').first().locator(':scope > div:not([hidden])'); return panel; }

test('composer grows, has unified radius, supports attachments and model selection', async ({ page }) => {
  const panel = await setup(page);
  await selectAssistant(panel);
  await expect(panel.locator('.message-composer label:not(.select__label--hidden)')).toHaveCount(0);
  const input = panel.getByRole('textbox', { name: 'Message your assistant' });
  const before = (await input.boundingBox())!.height;
  expect(before).toBeLessThan(50);
  await input.fill('First line\nSecond line\nThird line\nFourth line');
  expect((await input.boundingBox())!.height).toBeGreaterThan(before);
  await input.focus();
  expect(await input.evaluate(el => getComputedStyle(el).outlineStyle)).toBe('none');
  expect(await panel.locator('.message-composer').evaluate(el => getComputedStyle(el).borderRadius)).toBe('8px');
  await panel.locator('input[type=file]').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('sample notes') });
  await expect(panel.locator('.composer-attachments')).toContainText('notes.txt');
  await chooseOption(panel.getByRole('combobox', { name: 'Select model' }), 'Fast · Demo');
  await panel.getByRole('button', { name: 'Send', exact: true }).click();
  await expect(input).toHaveValue('');
  expect((await input.boundingBox())!.height).toBeLessThan(50);
  await expect(panel.locator('.message-attachments')).toContainText('notes.txt');
  await expect(panel.locator('.assistant-chat__message--assistant').last()).toContainText('I hear you');
  await panel.getByRole('button', { name: 'Message information', exact: true }).last().click();
  await expect(page.getByRole('dialog', { name: 'Message information' })).toContainText('fast');
  await page.keyboard.press('Escape');
  await page.evaluate(() => Object.defineProperty(navigator, 'mediaDevices', { value: undefined, configurable: true }));
  await panel.getByRole('button', { name: 'Voice input' }).click();
  await expect(panel.locator('.composer-notice')).toContainText('Recording is unavailable');
  await panel.screenshot({ path: `/tmp/molr-composer-${test.info().project.name}.png` });
});

test('composer hover and blank-area clicks focus the draft without hijacking controls', async ({ page }) => {
  const panel = await setup(page);
  const composer = panel.getByRole('form', { name: 'Message composer' });
  const input = panel.getByRole('textbox', { name: 'Message your assistant' });
  await panel.locator('.conversation-header h3').click();
  await page.mouse.move(0, 0);
  const idleBorder = await composer.evaluate(el => getComputedStyle(el).borderTopColor);
  await composer.hover();
  await expect(composer).not.toHaveCSS('border-top-color', idleBorder);
  await expect(composer).not.toHaveCSS('border-top-color', await composer.evaluate(el => getComputedStyle(el).color));
  await composer.click({ position: { x: 8, y: 8 } });
  await expect(input).toBeFocused();
  await input.fill('Keep this draft');
  const model = composer.getByRole('combobox', { name: 'Select model' });
  await model.click();
  await expect(model).toBeFocused();
  await model.press('ArrowDown');
  await expect(model).toContainText('Standard · Demo');
  await model.press('Escape');
  await expect(model).toContainText('Standard · Demo');
  await model.press('Space');
  await model.press('End');
  await model.press('Enter');
  await expect(model).toBeFocused();
  await expect(model).toContainText('Fast · Demo');
  await expect(input).toHaveValue('Keep this draft');
  await expect(panel.getByRole('log')).not.toContainText('Keep this draft');
  await selectAssistant(panel, '旅行助理');
  await expect(input).toHaveValue('');
  await selectAssistant(panel, 'Molr');
  await expect(input).toHaveValue('Keep this draft');
  await expect(model).toContainText('Fast · Demo');
});

