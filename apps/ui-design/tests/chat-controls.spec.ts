test('outgoing text and attachments track their own receipts and survive reloads', async ({ page }, info) => {
  const panel = await setup(page, info.project.name === 'mobile');
  await selectAssistant(panel);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.clock.install();
  await page.clock.pauseAt(Date.now() + 1000);
  const input = panel.getByRole('textbox', { name: 'Message your assistant' });
  await input.fill('A quiet afternoon');
  await input.press('Enter');
  const receipts = panel.locator('.assistant-chat__message--user .message-read-status');
  await expect(receipts).toHaveText(['Unread']);
  await panel.locator('input[type=file]').setInputFiles({ name: 'receipt.txt', mimeType: 'text/plain', buffer: Buffer.from('notes') });
  await input.press('Enter');
  await expect(receipts).toHaveText(['Unread', 'Unread']);
  await page.clock.runFor(650);
  await expect(receipts).toHaveText(['Read', 'Unread']);
  await expect(panel.locator('.assistant-chat__message--assistant .message-read-status')).toHaveCount(0);
  await expect(panel.locator('.ui-chat-bubble .message-read-status')).toHaveCount(0);
  await panel.locator('.assistant-chat__messages').screenshot({ path: `/tmp/molr-message-receipts-${info.project.name}.png` });

  await page.reload();
  if (info.project.name === 'mobile') await page.locator('#interfaces').getByRole('tab', { name: 'Mobile', exact: true }).click();
  await selectAssistant(panel);
  await expect(receipts).toHaveText(['Read', 'Unread']);
  await page.clock.runFor(700);
  await expect(receipts).toHaveText(['Read', 'Read']);
  await expect(panel.locator('.assistant-chat__message--user').last()).toContainText('receipt.txt');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('legacy receipts match replies within each assistant', async ({ page }) => {
  const panel = await setup(page);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.clock.install();
  await page.clock.pauseAt(Date.now() + 1000);
  await page.evaluate(() => {
    const key = 'molr-assistant-prototype-v1';
    const state = JSON.parse(localStorage.getItem(key)!);
    state.assistants[0].messages.push({ id: 'u-legacy', role: 'user', text: 'Earlier question' }, { id: 'a-legacy', role: 'assistant', text: 'Earlier answer' });
    state.assistants[1].messages.push({ id: 'u-legacy', role: 'user', text: 'Travel question' });
    state.assistants[1].pendingReply = { id: 'a-legacy', role: 'assistant', text: 'Travel answer' };
    localStorage.setItem(key, JSON.stringify(state));
  });
  await page.reload();
  await selectAssistant(panel);
  await expect(panel.locator('.message-read-status')).toHaveText(['Read']);
  await selectAssistant(panel, '旅行助理');
  await expect(panel.locator('.message-read-status')).toHaveText(['Unread']);
  await page.clock.runFor(700);
  await expect(panel.locator('.message-read-status')).toHaveText(['Read']);
});

test('todos manage personal and assistant responsibilities independently of tasks', async ({ page }) => {
  const panel = await setup(page);
  const menu = panel.getByRole('navigation', { name: 'Workspace navigation' });
  await expect(menu.getByRole('button', { name: 'Tasks', exact: true })).toHaveCount(0);
  await menu.getByRole('button', { name: 'Plans', exact: true }).click();
  await panel.getByRole('button', { name: 'New plan' }).click();
  const form = panel.getByRole('form', { name: 'Plan editor' });
  await form.getByRole('textbox', { name: 'What needs doing?' }).fill('Check my packing list');
  await form.getByText('More options', { exact: true }).click();
  await chooseOption(form.getByRole('combobox', { name: 'Owner' }), '旅行助理');
  await form.getByRole('button', { name: 'Save plan' }).click();
  const item = panel.locator('.plan-row').filter({ hasText: 'Check my packing list' });
  await expect(item).toContainText('旅行助理');
  await item.getByRole('checkbox').check();
  await expect(item).toHaveAttribute('data-completed', 'true');
  await page.reload();
  await menu.getByRole('button', { name: 'Plans', exact: true }).click();
  await chooseOption(panel.getByRole('combobox', { name: 'Status', exact: true }), 'Completed');
  await expect(item.getByRole('checkbox')).toBeChecked();
  await item.getByRole('button', { name: 'Edit', exact: true }).click();
  await chooseOption(form.getByRole('combobox', { name: 'Owner' }), 'Me');
  await form.getByRole('button', { name: 'Save plan' }).click();
  await expect(item).toContainText('Me');
  await item.getByRole('button', { name: 'Delete', exact: true }).click();
  await item.getByRole('button', { name: 'Confirm delete' }).click();
  await expect(item).toHaveCount(0);
});
