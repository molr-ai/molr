// Real desktop -> installer -> Runtime handoff, with an isolated profile/service.
import assert from 'node:assert/strict';
import { _electron as electron, expect } from '@playwright/test';
import { mkdirSync, mkdtempSync, existsSync, readFileSync, rmSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { tmpdir } from 'node:os';
import { LocalRuntime } from '../dist/main/runtime/local.js';
const root = resolve(import.meta.dirname, '../../..');
const evidence = join(root, '.cache/acceptance/installation'); mkdirSync(evidence, {recursive:true});
const directory = mkdtempSync(join(tmpdir(), 'molr-installation-ui-'));
const profile = join(directory, 'desktop');
const packageRoot = resolve(process.env.MOLR_DESKTOP_RUNTIME_PACKAGE || join(root, `.cache/release/${process.platform}-${process.arch==='arm64'?'arm64':'amd64'}/molr`));
const env = {...process.env, MOLR_DESKTOP_DATA:profile, MOLR_DESKTOP_RUNTIME:packageRoot, XDG_CONFIG_HOME:join(directory,'config'), XDG_DATA_HOME:join(directory,'data'), XDG_CACHE_HOME:join(directory,'cache')};
delete env.ELECTRON_RUN_AS_NODE; delete env.MOLR_DESKTOP_DEV_URL;
let app;
try {
 app = await electron.launch({args:[join(root,'apps/desktop'),...(process.env.MOLR_DESKTOP_TEST_HEADLESS==='1'?['--ozone-platform=headless']:[])],env,chromiumSandbox:true,timeout:30000});
 const manager = await app.firstWindow();
 await expect(manager.getByRole('heading',{name:'你想在哪里使用 Molr？'})).toBeVisible();
 await manager.getByRole('button',{name:'安装到这台电脑'}).click();
 await manager.getByLabel('管理员用户名').fill('chosen-admin');
 await manager.getByLabel('密码',{exact:true}).fill('desktop-install-fixture-2026');
 await manager.getByLabel('确认密码',{exact:true}).fill('desktop-install-fixture-2026');
 await manager.screenshot({path:join(evidence,'administrator-form.png')});
 await manager.getByRole('button',{name:'安装并启动'}).click();
 await expect.poll(async()=>{const message=(await manager.locator('.ui-toast--danger').allTextContents()).join(''); if(message) throw new Error(message); return manager.getByRole('heading',{name:'选择连接'}).isVisible();},{timeout:120000}).toBe(true);
 const installed = await manager.evaluate(()=>window.molrDesktop.state());
 assert.equal(installed.view,'manager'); assert.equal(installed.local.installed,true); assert.equal(installed.connections.length,1);
 const record=JSON.parse(readFileSync(installed.local.record,'utf8'));
 assert(!existsSync(join(record.data_dir,'initial-password')));
 assert(!readFileSync(join(profile,'connections.json'),'utf8').includes('token='));
 assert(!readFileSync(join(profile,'runtime','maintenance.log'),'utf8').includes('desktop-install-fixture-2026'));
 await manager.screenshot({path:join(evidence,'installed-list.png')});
 let exchanges=0;
 app.context().on('request',request=>{if(new URL(request.url()).pathname==='/api/auth/login-links/redeem')exchanges++;});
 await manager.getByRole('button',{name:'连接',exact:true}).click();
 await expect.poll(()=>manager.evaluate(async()=>(await window.molrDesktop.state()).view),{timeout:30000}).toBe('runtime');
 const runtimePage=app.context().pages().find(p=>p.url().startsWith(installed.local.url)); assert(runtimePage);
 await expect(runtimePage.locator('.setup-page')).toBeVisible({timeout:30000});
 assert.equal(exchanges,1);
 await expect(runtimePage.getByRole('button',{name:/^(确认登录|Confirm sign-in)$/})).toHaveCount(0);
 const health=await runtimePage.evaluate(async()=>{const response=await fetch('/api/sandbox');if(!response.ok)throw new Error('Capability check failed');return response.json();});
 assert.equal(health.Enabled,true);assert.equal(health.Capabilities.Reason,'available');
 for(const name of ['Shell','FileIsolation','NetworkIsolation',...(process.platform==='linux'?['ProcessIsolation','ResourceLimits']:[])]) assert.equal(health.Capabilities[name],true,name);
 assert.equal(await runtimePage.evaluate(()=>window.molrApp.consumeInitialLogin()),false);
 await runtimePage.screenshot({path:join(evidence,'first-open-setup.png')});
 await runtimePage.reload(); await expect(runtimePage.locator('.setup-page')).toBeVisible(); assert.equal(exchanges,1);
 await manager.evaluate(()=>window.molrDesktop.manager());
 await expect(manager.getByRole('heading',{name:'选择连接'})).toBeVisible();
 await manager.getByRole('button',{name:'添加连接',exact:true}).click();
 await expect(manager.getByRole('heading',{name:'连接远程服务'})).toBeVisible();
 console.log('Native installation UI passed: chosen administrator, no password file, list after install, automatic single-use first login, persistent session, authenticated sandbox capabilities.');
} finally {
 await app?.close();
 Object.assign(process.env,{XDG_CONFIG_HOME:env.XDG_CONFIG_HOME,XDG_DATA_HOME:env.XDG_DATA_HOME,XDG_CACHE_HOME:env.XDG_CACHE_HOME});
 const runtime = new LocalRuntime(packageRoot,join(profile,'runtime'));
 const state = await runtime.status();
 if(state.installed) await runtime.action('uninstall');
 rmSync(directory,{recursive:true,force:true});
}
