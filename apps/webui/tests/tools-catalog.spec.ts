import { expect, test } from '@playwright/test';

test('tool catalog combines categories and search, opens details and restores focus', async ({ page }) => {
  await page.goto('/#/resources');
  if (!(await page.request.get('/api/auth/me')).ok()) {
    await page.getByLabel('Username', { exact: true }).fill('owner');
    await page.getByLabel('Password', { exact: true }).fill(process.env.MOLR_E2E_PASSWORD ?? 'webui-e2e-password-2026!');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  }
  await page.getByRole('tab', { name: 'Tools', exact: true }).click();
  const catalog = page.locator('.tools-catalog');
  const rows = catalog.locator('.tools-catalog-row');
  await expect(rows.first().locator('.tools-catalog-copy > span')).toHaveCSS('-webkit-line-clamp', '2');
  const response = await page.request.get('/api/tools');
  expect(response.ok()).toBe(true);
  const tools = await response.json();
  const visible = tools.filter((tool: { Name: string }) => !tool.Name.startsWith('plg_'));
  await expect(rows).toHaveCount(visible.length);
  const filters = page.getByRole('group', { name: 'Tool categories' });
  await filters.getByRole('button', { name: /Files and workspace/ }).click();
  await expect(rows).toHaveCount(visible.filter((tool: { Name: string }) => tool.Name.startsWith('file_')).length);
  const search = page.getByRole('searchbox', { name: 'Search tools by name or function' });
  await search.fill('  FILE_READ  ');
  await expect(rows).toHaveCount(1);
  await expect(rows).toContainText('Read file');
  await rows.first().focus();
  await page.keyboard.press('Enter');
  const detail = page.getByRole('dialog', { name: 'Read file', exact: true });
  await expect(detail).toBeVisible();
  await expect(detail).toContainText('file_read');
  await expect(detail).toContainText('Required actions');
  const definition = visible.find((tool: { Name: string }) => tool.Name === 'file_read');
  await expect(detail.getByRole('tab', { name: 'Model tool description', exact: true })).toHaveAttribute('aria-selected', 'true');
  expect(await detail.locator('.tool-catalog-model-description').textContent()).toBe(definition.Description);
  await expect(detail.locator('pre')).toBeHidden();
  await detail.getByRole('tab', { name: 'Input schema', exact: true }).click();
  await expect(detail.locator('pre')).toHaveText(JSON.stringify(visible.find((tool: { Name: string }) => tool.Name === 'file_read').InputSchema, null, 2));
  await page.keyboard.press('Escape');
  await expect(detail).toBeHidden();
  await expect(rows.first()).toBeFocused();
  await rows.first().click();
  await expect(detail.getByRole('tab', { name: 'Model tool description', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.keyboard.press('Escape');
  await expect(detail).toBeHidden();
  await expect(rows.first()).toBeFocused();
  await expect(search).toHaveValue('  FILE_READ  ');
  await search.fill('plan_manage');
  await expect(rows).toHaveCount(0);
  await expect(catalog).toContainText('No matching results');
  await filters.getByRole('button', { name: /Plans/ }).click();
  await expect(rows).toHaveCount(1);
  await expect(rows).not.toContainText('Write or publish');
  await expect(rows.locator('.tools-catalog-effect')).toHaveCount(0);
  await search.fill('no-such-tool');
  await catalog.getByRole('button', { name: 'Clear filters', exact: true }).click();
  await expect(search).toHaveValue('');
  await expect(rows).toHaveCount(visible.length);
  await expect(filters.getByRole('button', { name: /^All / })).toHaveAttribute('aria-pressed', 'true');
  await search.fill('shell_execute');
  await rows.first().click();
  const shell = page.getByRole('dialog', { name: 'Execute shell', exact: true });
  await expect(shell).toBeVisible();
  expect(await shell.locator('.tool-catalog-model-description').textContent()).toBe(visible.find((tool: { Name: string }) => tool.Name === 'shell_execute').Description);
  expect(await shell.locator('.ui-dialog__body').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await shell.getByRole('tab', { name: 'Input schema', exact: true }).click();
  expect(await shell.locator('.ui-dialog__body').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.keyboard.press('Escape');
  await expect(shell).toBeHidden();
  expect(await catalog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
