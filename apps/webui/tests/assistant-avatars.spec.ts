import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
const port = process.env.MOLR_TEST_PORT ?? '5193';
const base = `http://127.0.0.1:${port}`;
async function post(page: Page, path: string, data: object) {
 const csrf = (await page.context().cookies()).find(c => c.name === `molr_dev_csrf_p${port}`)!.value;
 const response = await page.request.post(path, { headers: { Origin: base, 'X-CSRF-Token': csrf }, data: { ...data, Mutation: { IdempotencyKey: crypto.randomUUID() } } });
 expect(response.status(), await response.text()).toBe(200); return response.json();
}
test('optional avatars persist presets, uploads, clearing and cloning', async ({ page }, info) => {
 await page.goto('/');
 await page.getByLabel('Username', { exact: true }).fill('owner');
 await page.getByLabel('Password', { exact: true }).fill(process.env.MOLR_AVATAR_TEST_PASSWORD ?? 'webui-e2e-password-2026!');
 await page.getByRole('button', { name: 'Sign in', exact: true }).click();
 await expect(page.getByRole('navigation', { name: 'Molr' })).toBeVisible();
 const name = `Avatar ${info.project.name}-${Date.now()}`, origin = `http://127.0.0.1:${process.env.MOLR_E2E_MODEL_PORT ?? 18882}`;
 const resource = await post(page, '/api/resources', { Name: name, Kind: 'model', Provider: 'openai-compatible', Binding: { Endpoint: origin, AllowedOrigins: [origin], Models: [{ Name: name, ContextLimit: 32768, SupportsTools: true, Pricing: { Currency: 'USD', InputMicrosPerMillion: 0, CachedInputMicrosPerMillion: 0, OutputMicrosPerMillion: 0 } }] } });
 const models = await (await page.request.get('/api/models')).json();
 const model = models.find((m: any) => m.ResourceID === resource.ID);
 const plain = await post(page, '/api/assistants', { Name: name, ModelID: model.ID, Budget: { Limit: { Currency: 'USD', Micros: 0 }, Period: 'daily' } });
 await page.goto(`/#/assistants/${plain.ID}`);
 const open = async () => { await page.locator('.chat-assistant-info').click(); await expect(page.getByRole('group', { name: 'Preset avatars' })).toBeVisible(); };
 const save = async () => { await page.locator('.assistant-info').getByRole('button', { name: 'Save', exact: true }).click(); await expect(page.getByRole('group', { name: 'Preset avatars' })).toHaveCount(0); };
 const get = async () => (await page.request.get(`/api/assistants/${plain.ID}`)).json();
 await open(); await expect(page.getByRole('img', { name: 'Avatar preview' })).toHaveText('A');
 await page.getByRole('button', { name: 'Fox', exact: true }).click(); await save();
 await expect.poll(async () => (await get()).Avatar).toBe('preset:fox');
 await page.reload(); await open();
 await expect(page.getByRole('button', { name: 'Fox', exact: true })).toHaveAttribute('aria-pressed', 'true');
 await page.locator('input[type=file][accept="image/png,image/jpeg,image/webp"]').setInputFiles({ name: 'bad.png', mimeType: 'image/png', buffer: Buffer.from('not an image') });
 await expect(page.getByRole('alert')).toContainText('Unable to read this image');
 await expect(page.getByRole('button', { name: 'Fox', exact: true })).toHaveAttribute('aria-pressed', 'true');
 const upload = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 600; c.height = 400; const ctx = c.getContext('2d')!; ctx.fillStyle = '#6d9e81'; ctx.fillRect(0, 0, 600, 400); return c.toDataURL('image/png').split(',')[1]; });
 await page.locator('input[type=file][accept="image/png,image/jpeg,image/webp"]').setInputFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: Buffer.from(upload, 'base64') });
 await expect(page.locator('.assistant-avatar-preview img')).toBeVisible();
 await save(); await page.reload(); await open();
 await expect(page.locator('.assistant-avatar-preview img')).toBeVisible();
 expect((await get()).Avatar).toMatch(/^data:image\/jpeg;base64,/);
 const clone = await post(page, '/api/assistants/clone', { SourceID: plain.ID, Name: `${name} copy` });
 expect(clone.Avatar).toBe((await get()).Avatar);
 await page.getByRole('button', { name: 'Clear', exact: true }).click(); await save();
 await expect.poll(async () => (await get()).Avatar).toBe('');
 await page.reload(); await open(); await expect(page.getByRole('img', { name: 'Avatar preview' })).toHaveText('A');
 await page.locator('.assistant-info').getByRole('button', { name: 'Cancel', exact: true }).click();
 if (info.project.name === 'mobile') await page.getByRole('button', { name: 'Back to assistants', exact: true }).click();
 await page.getByRole('button', { name: 'Hire new assistant', exact: true }).first().click();
 const hire = page.getByRole('dialog', { name: 'Hire new assistant', exact: true });
 await hire.getByRole('textbox', { name: 'Assistant name' }).fill(`${name} hired`);
 await hire.getByRole('button', { name: 'Robot', exact: true }).click();
 await hire.getByRole('spinbutton', { name: 'Spending limit (USD)', exact: true }).fill('0');
 await hire.getByRole('button', { name: 'Hire new assistant', exact: true }).click(); await expect(hire).not.toBeVisible();
 await expect(page.locator('.chat-header h1')).toHaveText(`${name} hired`);
 await page.getByRole('textbox', { name: 'Message your assistant', exact: true }).fill('Hello'); await page.getByRole('button', { name: 'Send', exact: true }).click();
 await expect(page.locator('.ui-chat-message--assistant .ui-chat-avatar svg').first()).toBeVisible({ timeout: 20000 });
 if (info.project.name === 'mobile') await page.getByRole('button', { name: 'Back to assistants', exact: true }).click();
 await expect(page.getByRole('button', { name: `${name} hired`, exact: true }).locator('.ui-assistant-avatar svg')).toBeVisible();
});
