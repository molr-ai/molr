import { test, expect } from '@playwright/test';

test('semantic memory directories, rename, editing and forgetting persist through real APIs', async ({ page }, info) => {
  await page.goto('/#/account/memory');
  await page.getByRole('textbox', { name: 'Username', exact: true }).fill('owner');
  await page.getByLabel('Password', { exact: true }).fill('webui-e2e-password-2026!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.locator('.memory-workspace')).toBeVisible();
  const folder = `用户偏好-${info.project.name}`;
  const dialog = page.getByRole('dialog');
  await page.getByRole('button', { name: 'New folder', exact: true }).click();
  await dialog.getByLabel('Folder name').fill(folder);
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: folder, exact: true }).click();
  await page.getByRole('button', { name: 'New file', exact: true }).click();
  await dialog.getByLabel('Descriptive filename (including .md)').fill('汇报偏好.md');
  await dialog.locator('textarea').fill('汇报时先给结论');
  await dialog.getByLabel('Conditions', { exact: true }).fill('每周汇报');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Rename / move', exact: true }).click();
  await dialog.getByLabel('New path (relative to memory folder)').fill(`${folder}/沟通偏好.md`);
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: folder, exact: true }).click();
  await expect(page.getByRole('button', { name: '汇报偏好.md', exact: true })).not.toBeVisible();
  await page.getByRole('button', { name: '沟通偏好.md', exact: true }).click();
  await expect(dialog.locator('textarea')).toHaveValue('汇报时先给结论');
  await expect(dialog.getByLabel('Conditions', { exact: true })).toHaveValue('每周汇报');
  await dialog.locator('textarea').fill('先给结论，再给必要细节');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  const row = page.locator('.memory-workspace .settings-row-item').filter({ hasText: '沟通偏好.md' });
  await row.getByRole('button', { name: 'Forget', exact: true }).click();
  await dialog.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(row).not.toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: folder, exact: true }).click();
  await expect(row).not.toBeVisible();
});
