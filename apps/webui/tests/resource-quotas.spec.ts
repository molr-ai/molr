import { test, expect, type Page } from '@playwright/test';
const port = process.env.MOLR_TEST_PORT ?? process.env.MOLR_E2E_PORT ?? '5193';
const base = `http://127.0.0.1:${port}`;
async function post(page: Page, path: string, data: object) {
  const csrf = (await page.context().cookies()).find(c => c.name === `molr_dev_csrf_p${port}`)!.value;
  const reply = await page.request.post(path, { headers: { Origin: base, 'X-CSRF-Token': csrf }, data: { ...data, Mutation: { IdempotencyKey: crypto.randomUUID() } } });
  expect(reply.status(), await reply.text()).toBe(200);
  return reply.json();
}
test.skip(process.env.MOLR_E2E_SANDBOX_SERVICE !== '1', 'Requires delegated Linux sandbox services');
test('grouped compute and network quotas preserve owner edits and fund automatic networking', async ({ page }, info) => {
  test.setTimeout(120_000);
  await page.goto('/');
  await page.getByLabel('Username', { exact: true }).fill('owner');
  await page.getByLabel('Password', { exact: true }).fill('webui-e2e-password-2026!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Molr' })).toBeVisible();
  const sandbox = await (await page.request.get('/api/sandbox')).json();
  expect(sandbox.Capabilities.Reason).toBe('available');
  const name = `Permission quota ${info.project.name} ${Date.now()}`;
  const origin = `http://127.0.0.1:${process.env.MOLR_E2E_MODEL_PORT ?? 18882}`;
  const provider = await post(page, '/api/resources', { Name: name, Kind: 'model', Provider: 'openai-compatible', Binding: { Endpoint: origin, AllowedOrigins: [origin], Models: [{ Name: name, ContextLimit: 65536, SupportsTools: true, Pricing: { Currency: 'USD', InputMicrosPerMillion: 0, CachedInputMicrosPerMillion: 0, OutputMicrosPerMillion: 0 } }] } });
  await post(page, '/api/sandboxes/resource', { SandboxID: 'local', Kind: 'network', SourceID: 'preset:host', Name: `Quota network ${info.project.name}` });
  const models = await (await page.request.get('/api/models')).json();
  const assistant = await post(page, '/api/assistants', { Name: name, ModelID: models.find((m: { ResourceID: string }) => m.ResourceID === provider.ID).ID, Budget: { Limit: { Currency: 'USD', Micros: 0 }, Period: 'daily' } });
  await page.goto(`/#/assistants/${assistant.ID}`);
  await page.getByRole('textbox', { name: 'Message your assistant', exact: true }).fill('Request compute and network quotas together.');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  const card = page.locator('.permission-request-card');
  await expect(card).toContainText('Download the quota verification file.', { timeout: 60_000 });
  await card.getByRole('button', { name: 'Review permission', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Review permission', exact: true });
  await expect(dialog.locator('.ui-date-time-picker')).toHaveCount(1);
  await dialog.getByRole('button', { name: '7 days', exact: true }).click();
  await dialog.locator('.permission-review-item').filter({ hasText: 'Shared compute quota' }).locator('summary').click();
  await expect(dialog.getByLabel('CPU capacity (cores)', { exact: true })).toHaveValue('2');
  await dialog.getByLabel('Memory limit (MiB)', { exact: true }).fill('1');
  await dialog.locator('.permission-review-item').filter({ hasText: 'Shared compute quota' }).locator('summary').click();
  await dialog.getByRole('button', { name: 'Approve permission', exact: true }).click();
  await expect(dialog.getByLabel('Memory limit (MiB)', { exact: true })).toBeVisible();
  await dialog.getByLabel('Memory limit (MiB)', { exact: true }).fill('768');
  await dialog.locator('.permission-review-item').filter({ hasText: 'Shared compute quota' }).locator('summary').click();
  await dialog.locator('.permission-review-item').filter({ hasText: 'Download the quota verification file.' }).locator('summary').click();
  await expect(dialog.getByLabel('Total concurrent connections', { exact: true })).toHaveValue('32');
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await dialog.getByRole('button', { name: 'Approve permission', exact: true }).click();
  await expect(card).toContainText('Approved');
  await expect(page.locator('.chat-history')).toContainText('Permission approved; current grants checked before continuing.', { timeout: 60000 });
  const requests = await (await page.request.get(`/api/permission-requests?assistant_id=${assistant.ID}`)).json();
  expect(requests[0].GrantedAll).toHaveLength(2);
  const compute = requests[0].GrantedAll.find((g: { Constraints?: { compute?: object } }) => g.Constraints?.compute);
  const network = requests[0].GrantedAll.find((g: { Constraints?: { network?: object } }) => g.Constraints?.network);
  expect(network.ExpiresAt).toBe(compute.ExpiresAt);
  expect(Date.parse(compute.ExpiresAt)).toBeGreaterThan(Date.now() + 6 * 86400000);
  expect(compute.Constraints.compute.memory_bytes).toBe(768 * 1048576);
  const usage = await (await page.request.get(`/api/resource-usage?assistant_id=${assistant.ID}&resource_id=${network.ResourceID}`)).json();
  expect(usage.Network.UsedBytes).toBeGreaterThan(1024);
  expect(usage.Network.Connections).toBe(0);
  await page.reload();
  await expect(card).toContainText('768 MiB');
  await expect(card.locator('.permission-request-expiry')).toHaveCount(1);
  await page.screenshot({ path: info.outputPath('quota-approved.png') });
});
