import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
const port = process.env.MOLR_TEST_PORT ?? '5193', base = `http://127.0.0.1:${port}`;
async function post(page: Page, path: string, data: object) {
  const csrf = (await page.context().cookies()).find(c => c.name === `molr_dev_csrf_p${port}`)!.value;
  const result = await page.request.post(path, { headers: { Origin: base, 'X-CSRF-Token': csrf }, data: { ...data, Mutation: { IdempotencyKey: crypto.randomUUID() } } });
  expect(result.status(), await result.text()).toBe(200); return result.json();
}
test('slash completion, compression event, live status and retained history', async ({ page }, info) => {
  await page.goto('/');
  await page.getByLabel('Username', { exact: true }).fill('owner');
  await page.getByLabel('Password', { exact: true }).fill('webui-e2e-password-2026!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Molr' })).toBeVisible();
  const name = `Compression ${info.project.name}-${Date.now()}`, origin = `http://127.0.0.1:${process.env.MOLR_E2E_MODEL_PORT ?? 18882}`;
  const resource = await post(page, '/api/resources', { Name: name, Kind: 'model', Provider: 'openai-compatible', Binding: { Endpoint: origin, AllowedOrigins: [origin], Models: [{ Name: name, ContextLimit: 32768, SupportsTools: true, Pricing: { Currency: 'USD', InputMicrosPerMillion: 0, CachedInputMicrosPerMillion: 0, OutputMicrosPerMillion: 0 } }] } });
  const models = await (await page.request.get('/api/models')).json();
  const assistant = await post(page, '/api/assistants', { Name: name, ModelID: models.find((m: any) => m.ResourceID === resource.ID).ID, Budget: { Limit: { Currency: 'USD', Micros: 0 }, Period: 'daily' } });
  await page.goto(`/#/assistants/${assistant.ID}`);
  const input = page.getByRole('textbox', { name: 'Message your assistant', exact: true });
  await input.fill('Keep these requirements and evidence. '.repeat(70));
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  const status = async () => (await (await page.request.get(`/api/assistants/${assistant.ID}/status`)).json());
  await expect(page.locator('.ui-chat-message--assistant')).toHaveCount(1);
  await expect.poll(async () => (await status()).State).toBe('idle');
  const count = await page.locator('.ui-chat-message').count();
  await input.fill('/');
  await expect(page.getByRole('listbox', { name: 'Commands' })).toBeVisible();
  await expect(page.getByRole('option')).toContainText('/compress');
  await input.press('Escape');
  await expect(page.getByRole('listbox', { name: 'Commands' })).toBeHidden();
  await expect(input).toHaveValue('/');
  await input.fill('/com');
  await input.press('Enter');
  await expect(input).toHaveValue('/compress');
  await expect(page.getByRole('listbox', { name: 'Commands' })).toBeHidden();
  expect((await status()).Context.Compressions).toBe(0);
  await input.press('Enter');
  await expect(input).toHaveValue('');
  await expect(page.locator('.chat-header')).toContainText('Compressing context');
  await page.reload();
  await expect.poll(async () => (await status()).Compression?.State).toBe('succeeded');
  await expect(page.locator('.chat-header')).not.toContainText('Compressing context');
  await expect(page.locator('.ui-chat-message')).toHaveCount(count);
  expect((await status()).Context.Compressions).toBe(1);
  const jobs = await (await page.request.get(`/api/jobs?assistant_id=${assistant.ID}`)).json();
  const compression = jobs.Items.filter((job: any) => job.Event.Kind === 'context_compression_requested');
  expect(compression).toHaveLength(1); expect(compression[0].Event.DeliveryMode).toBe('after_step');
  await input.fill('/work/file.txt');
  await expect(page.getByRole('listbox', { name: 'Commands' })).toBeHidden();
  await input.fill('Continue after compression.');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await expect(page.locator('.ui-chat-message--assistant')).toHaveCount(2);
  await expect.poll(async () => (await status()).State).toBe('idle');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
