import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, chmodSync, renameSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(root);
const arch = process.env.MOLR_ARCH || ({ x64: 'amd64', arm64: 'arm64' }[process.arch]);
if (!['amd64', 'arm64'].includes(arch)) throw new Error('MOLR_ARCH must be amd64 or arm64');
const version = process.env.MOLR_VERSION || '0.1.0-local';
if (!/^[0-9][0-9A-Za-z.-]*$/.test(version)) throw new Error('Invalid MOLR_VERSION');
const output = resolve(process.env.MOLR_DIST_DIR || 'dist/releases');
const stage = resolve('.cache/release', `linux-${arch}`, 'molr');
const run = (cmd, args, options = {}) => execFileSync(cmd, args, { stdio: 'inherit', ...options });
run('npm', ['run', 'check:release']);
run('npm', ['run', 'check:licenses']);
const commit = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
run('npm', ['run', 'build:webui'], { env: { ...process.env, MOLR_VERSION: version, MOLR_COMMIT: commit } });
const embedded = resolve('runtime/internal/webassets/dist');
rmSync(embedded, { recursive: true, force: true });
cpSync('apps/webui/dist', embedded, { recursive: true });
rmSync(stage, { recursive: true, force: true });
mkdirSync(`${stage}/bin`, { recursive: true });
mkdirSync(`${stage}/scripts`, { recursive: true });
for (const name of ['LICENSE', 'THIRD_PARTY_NOTICES.md']) cpSync(`${root}/${name}`, `${stage}/${name}`);
const go = process.env.GO || 'go';
const buildTime = new Date().toISOString();
run(go, ['build', '-trimpath', '-tags', 'webui', '-ldflags', `-X molr.ai/runtime/internal/buildinfo.Version=${version} -X main.commit=${commit} -X main.builtAt=${buildTime}`, '-o', `${stage}/bin/molr-server`, './cmd/molr-server'], { cwd: resolve('runtime'), env: { ...process.env, CGO_ENABLED: '0', GOOS: 'linux', GOARCH: arch, GOTOOLCHAIN: `go${readFileSync('runtime/.go-version', 'utf8').trim()}`, GOCACHE: process.env.GOCACHE || resolve('.cache/go-build'), GOMODCACHE: process.env.GOMODCACHE || resolve('.cache/go-mod') } });
const binary = `${stage}/bin/molr-server`;
chmodSync(binary, 0o755);
const description = execFileSync('file', [binary], { encoding: 'utf8' });
if (!description.includes('statically linked')) throw new Error('Runtime must be statically linked');
for (const name of ['install-linux.sh', 'install-linux.py', 'install_layout.py', 'uninstall-linux.sh', 'uninstall-linux.py']) cpSync(`runtime/scripts/${name}`, `${stage}/scripts/${name}`);
writeFileSync(`${stage}/release.json`, JSON.stringify({ version, commit, builtAt: buildTime, os: 'linux', arch }, null, 2));
mkdirSync(output, { recursive: true });
const filename = `molr_${version}_linux_${arch}.tar.gz`;
const releaseFiles = JSON.parse(readFileSync('scripts/release-policy.json', 'utf8')).releaseFiles;
const temporaryArchive = `${output}/${filename}.tmp`;
try {
  run('tar', ['-czf', temporaryArchive, '-C', dirname(stage), '--', ...releaseFiles.map(name => `molr/${name}`)]);
  run('python3', ['scripts/release_safety.py', 'release', temporaryArchive]);
  renameSync(temporaryArchive, `${output}/${filename}`);
} finally {
  rmSync(temporaryArchive, { force: true });
}
const sha256 = createHash('sha256').update(readFileSync(`${output}/${filename}`)).digest('hex');
writeFileSync(`${output}/${filename}.sha256`, `${sha256}  ${filename}\n`);
writeFileSync(`${output}/latest-linux-${arch}.json`, JSON.stringify({ version, file: filename, sha256 }, null, 2));
console.log(`Release: ${output}/${filename}`);
